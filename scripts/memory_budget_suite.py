OVERSIZED_STRUCTURED_FIXTURE = Path("_build/memory/fixtures/oversized_structured.ouro")
OVERSIZED_STRUCTURED_BYTES = 40960 + 4096


def write_oversized_structured_fixture() -> None:
    target = ROOT / OVERSIZED_STRUCTURED_FIXTURE
    target.parent.mkdir(parents=True, exist_ok=True)
    lines = ["-- generated by scripts/memory_budget_suite.py; must exceed the drive limit", ""]
    index = 0
    size = sum(len(line) + 1 for line in lines)
    while size <= OVERSIZED_STRUCTURED_BYTES:
        line = f"def oversized_{index} (n : Nat) : Nat := n;"
        lines.append(line)
        size += len(line) + 1
        index += 1
    target.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


@dataclass(frozen=True)
class Case:
    label: str
    budget_id: str
    cmd: list[str]
    description: str
    blocking: bool = True
    env: dict[str, str] = field(default_factory=dict)
    # One accepted exit code, or several when the verdict is not the point.
    expected_returncode: int | tuple[int, ...] = 0
    required_output: str | None = None

    def accepts_returncode(self, returncode: object) -> bool:
        if isinstance(self.expected_returncode, tuple):
            return returncode in self.expected_returncode
        return returncode == self.expected_returncode


