def largest_production_source() -> str:
    """Keep the budget on the largest input after refactors, not an old filename."""
    candidates = (path for scope in ("std", "compiler", "tools/analyze", "tools")
                  for path in (ROOT / scope).rglob("*.ouro"))
    largest = max(candidates, key=lambda path: (path.stat().st_size, path.as_posix()))
    return largest.relative_to(ROOT).as_posix()


